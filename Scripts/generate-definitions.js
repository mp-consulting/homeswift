#!/usr/bin/env node
// Generates Sources/Homeswift/Model/Definitions.swift from HAP-NodeJS's service and
// characteristic definitions (Apache-2.0).
//
//   node Scripts/generate-definitions.js <path to hap-nodejs> > Sources/Homeswift/Model/Definitions.swift

const path = require("path");
const root = process.argv[2];
if (!root) {
  console.error("usage: generate-definitions.js <path to hap-nodejs>");
  process.exit(1);
}
const hap = require(path.resolve(root, "dist/index.js"));
const version = require(path.resolve(root, "package.json")).version;

const keywords = new Set(["switch", "default", "in", "is", "as", "case", "class", "enum", "for", "if", "init", "let", "var", "func", "import", "operator", "protocol", "repeat", "return", "self", "struct", "subscript", "super", "throw", "true", "false", "try", "where", "while", "nil", "public", "private", "internal", "static", "extension", "deinit", "do", "else", "break", "continue", "fallthrough", "guard", "defer", "catch", "rethrows", "throws", "Type", "Protocol"]);

function camel(name) {
  // "PM2_5Density" -> "pm2_5Density", "CCAEnergy" -> "ccaEnergy", "WiFiX" -> "wiFiX"
  const m = name.match(/^([A-Z]+)(.*)$/);
  if (!m) return name;
  let [, caps, rest] = m;
  if (caps.length > 1 && /^[a-z]/.test(rest)) {
    rest = caps.slice(-1) + rest;
    caps = caps.slice(0, -1);
  }
  const out = caps.toLowerCase() + rest;
  return keywords.has(out) ? "`" + out + "`" : out;
}

function constantName(key) {
  // "UNSECURED" -> "unsecured", "CONTROL_LOCK_ENABLED" -> "controlLockEnabled"
  const parts = key.toLowerCase().split("_").filter(Boolean);
  let out = parts.map((p, i) => (i === 0 ? p : p[0].toUpperCase() + p.slice(1))).join("");
  if (/^[0-9]/.test(out)) out = "_" + out;
  return keywords.has(out) ? "`" + out + "`" : out;
}

function uuidLiteral(uuid) {
  const suffix = "-0000-1000-8000-0026BB765291";
  if (uuid.toUpperCase().endsWith(suffix)) {
    return "HAPUUID(0x" + uuid.slice(0, 8).replace(/^0+(?=.)/, "").toUpperCase() + ")";
  }
  return 'HAPUUID("' + uuid.toUpperCase() + '")';
}

const permMap = { pr: ".pairedRead", pw: ".pairedWrite", ev: ".events", aa: ".additionalAuthorization", tw: ".timedWrite", hd: ".hidden", wr: ".writeResponse" };
const num = (v) => String(v);

const charKeys = Object.keys(hap.Characteristic)
  .filter((k) => hap.Characteristic[k] && typeof hap.Characteristic[k] === "function" && hap.Characteristic[k].UUID)
  .sort();
const serviceKeys = Object.keys(hap.Service)
  .filter((k) => hap.Service[k] && typeof hap.Service[k] === "function" && hap.Service[k].UUID)
  .sort();

const byUUID = new Map();
const lines = [];
lines.push("// THIS FILE IS GENERATED by Scripts/generate-definitions.js - DO NOT EDIT.");
lines.push(`// Source: HAP-NodeJS ${version} definitions (Apache-2.0).`);
lines.push("");
lines.push("// swiftlint:disable all");
lines.push("");
lines.push("extension CharacteristicType {");
const constants = [];
const charNames = [];
for (const key of charKeys) {
  const Cls = hap.Characteristic[key];
  let c;
  try { c = new Cls(); } catch { continue; }
  const p = c.props;
  const name = camel(key);
  byUUID.set(Cls.UUID, name);
  const args = [`name: ${JSON.stringify(c.displayName)}`, `uuid: ${uuidLiteral(Cls.UUID)}`, `format: .${p.format}`];
  args.push(`permissions: [${p.perms.map((x) => permMap[x]).filter(Boolean).join(", ")}]`);
  if (p.unit) args.push(`unit: .${p.unit}`);
  if (p.minValue !== undefined && p.minValue !== null) args.push(`minValue: ${num(p.minValue)}`);
  if (p.maxValue !== undefined && p.maxValue !== null) args.push(`maxValue: ${num(p.maxValue)}`);
  if (p.minStep !== undefined && p.minStep !== null) args.push(`minStep: ${num(p.minStep)}`);
  if (p.maxLen !== undefined && p.maxLen !== null) args.push(`maxLength: ${p.maxLen}`);
  if (Array.isArray(p.validValues) && p.validValues.length) args.push(`validValues: [${p.validValues.join(", ")}]`);
  if (Array.isArray(p.validValueRanges)) args.push(`validValueRange: ${p.validValueRanges[0]}...${p.validValueRanges[1]}`);
  lines.push(`    public static let ${name} = CharacteristicType(${args.join(", ")})`);
  charNames.push(name);

  const statics = Object.keys(Cls).filter((s) => s !== "UUID" && typeof Cls[s] === "number");
  if (statics.length) constants.push({ key, statics: statics.map((s) => [constantName(s), Cls[s]]) });
}
lines.push("");
lines.push("    /// Every type above, to find one by its UUID (`known(uuid:)`).");
lines.push(`    public static let all: [CharacteristicType] = [${charNames.map((n) => "." + n).join(", ")}]`);
lines.push("}");
lines.push("");
lines.push("/// Named values for enumerated characteristics, e.g. `HAPConstants.LockCurrentState.secured`.");
lines.push("public enum HAPConstants {");
for (const { key, statics } of constants) {
  lines.push(`    public enum ${key} {`);
  const seen = new Set();
  for (const [n, v] of statics) {
    if (seen.has(n)) continue;
    seen.add(n);
    lines.push(`        public static let ${n}: Int = ${v}`);
  }
  lines.push("    }");
}
lines.push("}");
lines.push("");
lines.push("extension ServiceType {");
const serviceNames = [];
for (const key of serviceKeys) {
  const Cls = hap.Service[key];
  let s;
  try { s = new Cls("Sample", "sample"); } catch { continue; }
  const req = s.characteristics.map((c) => byUUID.get(c.UUID)).filter((n) => n && n !== "name");
  const opt = s.optionalCharacteristics.map((c) => byUUID.get(c.UUID)).filter(Boolean);
  const args = [`name: ${JSON.stringify(key)}`, `uuid: ${uuidLiteral(Cls.UUID)}`, `required: [${req.map((n) => "." + n).join(", ")}]`, `optional: [${opt.map((n) => "." + n).join(", ")}]`];
  lines.push(`    public static let ${camel(key)} = ServiceType(${args.join(", ")})`);
  serviceNames.push(camel(key));
}
lines.push("");
lines.push("    /// Every type above, to find one by its UUID (`known(uuid:)`).");
lines.push(`    public static let all: [ServiceType] = [${serviceNames.map((n) => "." + n).join(", ")}]`);
lines.push("}");
console.log(lines.join("\n"));
