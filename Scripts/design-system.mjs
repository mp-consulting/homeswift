// Syncs the public component explorer with production controls and generated HomeKit definitions.
// node Scripts/design-system.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import vm from "node:vm";
const root = fileURLToPath(new URL("..", import.meta.url));
const check = process.argv.includes("--check");
const definitions = readFileSync(join(root, "Sources/Homeswift/Model/Definitions.swift"), "utf8");
const permission = { pairedRead: "pr", pairedWrite: "pw", events: "ev", timedWrite: "tw", writeResponse: "wr", additionalAuthorization: "aa", hidden: "hd" };
const characteristics = [...definitions.matchAll(/public static let `?(\w+)`? = CharacteristicType\(name: "([^"]+)", uuid: HAPUUID\(([^)]+)\), format: \.(\w+), permissions: \[([^\]]*)\]([^\n]*)\)/g)].map(([, id, name, uuid, format, permissions, rest]) => {
  const entry = { id, type: name, uuid, format, permissions: [...permissions.matchAll(/\.(\w+)/g)].map((match) => permission[match[1]]) };
  if (entry.permissions.some((one) => !one)) throw new Error(`Unknown permission: ${id}`);
  for (const key of ["minValue", "maxValue", "minStep", "maxLength"]) {
    const found = rest.match(new RegExp(`${key}: ([\\d.eE+-]+)`));
    if (found) entry[key] = Number(found[1]);
  }
  const unit = rest.match(/unit: \.(\w+)/); if (unit) entry.unit = unit[1];
  const values = rest.match(/validValues: \[([^\]]*)\]/); if (values) entry.validValues = values[1].split(",").map(Number);
  return entry;
});
const services = [...definitions.matchAll(/public static let `?(\w+)`? = ServiceType\(name: "([^"]+)", uuid: HAPUUID\(([^)]+)\), required: \[([^\]]*)\], optional: \[([^\]]*)\]/g)].map(([, id, name, uuid, required, optional]) => ({
  id, name, uuid, required: [...required.matchAll(/\.(\w+)/g)].map((one) => one[1]), optional: [...optional.matchAll(/\.(\w+)/g)].map((one) => one[1]),
}));
const widgets = readFileSync(join(root, "Sources/HomeswiftUI/Web/widgets.js"), "utf8");
const plumbing = [...widgets.match(/const plumbing = new Set\(\[([\s\S]*?)\]\)/)[1].matchAll(/"([^"]+)"/g)].map((one) => one[1]);
for (const characteristic of characteristics) {
  characteristic.services = services.filter((service) => [...service.required, ...service.optional].includes(characteristic.id)).map((service) => service.id);
  characteristic.protocolOnly = plumbing.includes(characteristic.type) || ["data", "tlv8"].includes(characteristic.format);
}
const declarationCount = (type) => [...definitions.matchAll(new RegExp(`public static let [^\\n]+ = ${type}\\(`, "g"))].length;
if (characteristics.length !== declarationCount("CharacteristicType") || services.length !== declarationCount("ServiceType")) throw new Error("Definitions parser missed part of the catalog");
const ids = new Set(characteristics.map((one) => one.id));
for (const service of services) for (const id of [...service.required, ...service.optional]) if (!ids.has(id)) throw new Error(`Unknown characteristic in ${service.id}: ${id}`);
let stale = false;
const put = (path, data) => {
  const target = join(root, "site/design", path);
  if (check) { if (!existsSync(target) || !readFileSync(target).equals(Buffer.from(data))) { console.error(`Stale design-system asset: ${path}`); stale = true; } }
  else { mkdirSync(join(target, ".."), { recursive: true }); writeFileSync(target, data); }
};
put("catalog.js", `// Generated by Scripts/design-system.mjs; edit Definitions.swift's generator or production controls.\nwindow.HomeswiftDesignCatalog = ${JSON.stringify({ characteristics, services }, null, 2)};\n`);
for (const name of ["style.css", "common.js", "widgets.js", "remote.js", "camera.js", "i18n.js", "i18n-fr.js", "i18n-es.js", "i18n-pt.js"]) put(`runtime/${name}`, readFileSync(join(root, "Sources/HomeswiftUI/Web", name)));

// Fail on untranslated explorer UI, story descriptions, contract labels and characteristic names.
const catalogs = { fr: {}, es: {}, pt: {} };
const add = (code, strings) => { if (typeof code === "object") for (const [language, entries] of Object.entries(code)) add(language, entries); else Object.assign(catalogs[code], strings); };
for (const language of Object.keys(catalogs)) vm.runInNewContext(readFileSync(join(root, `Sources/HomeswiftUI/Web/i18n-${language}.js`), "utf8"), { HomeswiftI18n: { add } });
vm.runInNewContext(readFileSync(join(root, "site/design/translations.js"), "utf8"), { HomeswiftI18n: { add } });
const keys = new Set(["Foundations", "Widgets", "Characteristics", "All", "Small", "Medium", "Large", "Extra large", "XL", "Accent", "Text", "Secondary text", "Surface", "Success", "Warning", "Error", "Active tile", "Layout", "Interaction", "Chip", "Small control", "Control", "Group", "Card", "Panel", "Capsule"]);
for (const file of ["explorer.js", "canvas.js"]) {
  const text = readFileSync(join(root, "site/design", file), "utf8");
  for (const match of text.matchAll(/\b(?:t|note|pair)\("((?:[^"\\]|\\.)*)"/g)) keys.add(JSON.parse(`"${match[1]}"`));
}
const html = readFileSync(join(root, "site/design/index.html"), "utf8");
for (const match of html.matchAll(/<[a-z][^>]*\bdata-i18n\b[^>]*>/g)) {
  const text = html.slice(match.index + match[0].length).split("<")[0].trim();
  if (text) keys.add(text.replace(/&amp;/g, "&"));
  for (const attribute of match[0].matchAll(/(?:title|aria-label|placeholder|alt)="([^"]+)"/g)) keys.add(attribute[1]);
}
const context = { HomeswiftDesignCatalog: { characteristics, services }, structuredClone, window: {} };
vm.runInNewContext(readFileSync(join(root, "site/design/stories.js"), "utf8"), context);
for (const story of context.window.HomeswiftDesignStories.widgets) { keys.add(story.name); keys.add(story.description); story.build(); }
for (const c of characteristics) keys.add(c.type);
const missing = Object.entries(catalogs).flatMap(([language, strings]) => [...keys].filter(key => !strings[key]).map(key => `${language}: ${key}`));
if (missing.length) throw new Error(`Missing design-system translations:\n${missing.join("\n")}`);

if (stale) process.exitCode = 1;
else console.log(`${check ? "Checked" : "Synced"} ${characteristics.length} characteristics, ${services.length} services and production UI assets`);
